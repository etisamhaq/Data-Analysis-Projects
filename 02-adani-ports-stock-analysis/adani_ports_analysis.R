# Adani Ports (NSE: ADANIPORTS) 2007-2021: return, risk and market exposure for an investor.
#
# Data: daily NSE prices for one stock, listed as MUNDRAPORT until 16 Jan 2012 and ADANIPORTS after
# (Kaggle "NIFTY-50 Stock Market Data", Rohan Rao), plus the Nifty 50 index (Kaggle "Nifty Indices Dataset",
# Sudalai Rajkumar, version 7) as the market benchmark.
#
# Run from this folder:  Rscript adani_ports_analysis.R
# Uses the tested functions in R/, writes charts to figures/ and every quoted number to results/.

suppressPackageStartupMessages({
  library(tidyverse)
  library(lubridate)
  library(scales)
})
for (f in list.files("R", full.names = TRUE)) source(f)

dir.create("figures", showWarnings = FALSE)
dir.create("results", showWarnings = FALSE)
theme_set(theme_minimal(base_size = 11) +
            theme(plot.title = element_text(face = "bold"), panel.grid.minor = element_blank()))
BLUE <- "#2a78d6"; ORANGE <- "#eb6834"; GREY <- "#9a9993"; INK <- "#0b0b0b"
save_plot <- function(p, name, w = 9, h = 4.5) ggsave(file.path("figures", name), p, width = w, height = h, dpi = 150, bg = "white")
pct <- function(x, d = 1) sprintf(paste0("%.", d, "f%%"), 100 * x)
summary_lines <- c("# Adani Ports: results", "", "Generated by `adani_ports_analysis.R`. Do not edit by hand.", "")
add <- function(...) summary_lines <<- c(summary_lines, ...)

# ---- 1. Data ------------------------------------------------------------------------------
stock <- load_stock("data/ADANIPORTS.csv")
px <- stock$prices
index <- load_index("data/NIFTY50_INDEX.csv") %>% filter(Date >= min(px$Date), Date <= max(px$Date))
rets <- aligned_returns(px, index)

add("## Data", "",
    sprintf("- %d trading days, %s to %s; ticker MUNDRAPORT until %s, then ADANIPORTS.", nrow(px), min(px$Date),
            max(px$Date), stock$symbols$last[stock$symbols$Symbol == "MUNDRAPORT"]),
    sprintf("- Share split detected and adjusted: %s, ratio %d:1 (prev close %.1f, open %.1f).",
            stock$splits$date, as.integer(stock$splits$ratio), stock$splits$prev_close, stock$splits$open),
    sprintf("- `Trades` missing on %d days (not reported before June 2011); no rows dropped.", stock$missing_trades),
    sprintf("- %d days with both stock and Nifty 50 returns.", nrow(rets)), "")

# ---- 2. Return and risk vs the market ---------------------------------------------------------
perf <- tibble(
  series = c("Adani Ports", "Nifty 50 index"),
  annual_return = c(cagr(px$Close, px$Date), cagr(index$Close, index$Date)),
  volatility = c(annualised_volatility(rets$stock), annualised_volatility(rets$market)),
  return_to_risk = c(return_to_risk(rets$stock), return_to_risk(rets$market)),
  downside_return_to_risk = c(downside_return_to_risk(rets$stock), downside_return_to_risk(rets$market)),
  max_drawdown = c(max_drawdown(px$Close), max_drawdown(index$Close)))
write_csv(perf, "results/performance.csv")
add("## Return and risk vs the Nifty 50 (price only, dividends excluded)", "",
    "| | Annual return | Volatility | Return / risk | Downside return / risk | Max drawdown |", "|---|---|---|---|---|---|",
    sprintf("| %s | %s | %s | %.2f | %.2f | %s |", perf$series, pct(perf$annual_return), pct(perf$volatility),
            perf$return_to_risk, perf$downside_return_to_risk, pct(perf$max_drawdown, 0)), "")

growth <- bind_rows(px %>% transmute(Date, series = "Adani Ports", value = Close / first(Close) * 100),
                    index %>% transmute(Date, series = "Nifty 50 index", value = Close / first(Close) * 100))
save_plot(ggplot(growth, aes(Date, value, colour = series)) + geom_line(linewidth = 0.6) +
            scale_y_log10() + scale_colour_manual(values = c(BLUE, GREY)) +
            labs(title = "Growth of 100 invested at listing (log scale, price only)",
                 subtitle = sprintf("Adani Ports %s a year vs Nifty 50 %s, with %.1fx the volatility",
                                    pct(perf$annual_return[1]), pct(perf$annual_return[2]),
                                    perf$volatility[1] / perf$volatility[2]),
                 x = NULL, y = NULL, colour = NULL) + theme(legend.position = "top"), "05_vs_nifty.png")

save_plot(ggplot(px, aes(Date, Close)) + geom_line(colour = BLUE, linewidth = 0.5) +
            scale_y_log10(labels = label_number(prefix = "Rs ")) +
            labs(title = "Adani Ports share price, split-adjusted (log scale)",
                 subtitle = sprintf("%s a year from listing to April 2021, before dividends", pct(perf$annual_return[1])),
                 x = NULL, y = NULL, caption = "Source: NSE via Kaggle"), "01_price_log.png")

# ---- 3. Drawdowns ------------------------------------------------------------------------------
episodes <- bind_rows(
  drawdown_episode(px$Date, px$Close, "2008-01-01", "2009-12-31"),
  drawdown_episode(px$Date, px$Close, "2015-01-01", "2016-12-31"),
  drawdown_episode(px$Date, px$Close, "2020-01-01", "2020-12-31"))
write_csv(episodes, "results/drawdowns.csv")
add("## Largest falls", "", "| Peak | Trough | Fall | Recovered | Years peak to recovery |", "|---|---|---|---|---|",
    sprintf("| %s | %s | %s | %s | %.1f |", episodes$peak, episodes$trough, pct(episodes$fall, 0),
            episodes$recovered, episodes$years_to_recover), "")
save_plot(ggplot(px %>% mutate(dd = drawdown(Close)), aes(Date, dd)) + geom_area(fill = ORANGE, alpha = 0.85) +
            scale_y_continuous(labels = percent) +
            labs(title = "Drawdown: distance below the previous peak",
                 subtitle = "Three falls of more than 50%: 2008, 2015-16 and the 2020 COVID crash", x = NULL, y = NULL),
          "02_drawdowns.png", h = 4)

yearly <- px %>% group_by(year = year(Date)) %>%
  summarise(return = last(Close) / first(Close) - 1, .groups = "drop")
save_plot(ggplot(yearly, aes(factor(year), return, fill = return > 0)) + geom_col(width = 0.7) +
            geom_text(aes(label = percent(return, accuracy = 1), vjust = if_else(return > 0, -0.4, 1.3)), size = 3) +
            scale_fill_manual(values = c(`TRUE` = BLUE, `FALSE` = ORANGE), guide = "none") +
            scale_y_continuous(labels = percent, expand = expansion(mult = 0.12)) +
            labs(title = "Calendar-year price return", subtitle = "2007 starts at listing (27 Nov); 2021 runs to 30 April",
                 x = NULL, y = NULL), "03_yearly_returns.png")

# ---- 4. Market exposure --------------------------------------------------------------------------
mm <- market_model(rets)
periods <- list(c("2007-11-27", "2012-12-31"), c("2013-01-01", "2017-12-31"), c("2018-01-01", "2021-04-30"))
mm_periods <- map_dfr(periods, ~ market_model(filter(rets, Date >= as.Date(.x[1]), Date <= as.Date(.x[2]))) %>%
                        mutate(period = paste(substr(.x[1], 1, 4), "to", substr(.x[2], 1, 4))))
write_csv(bind_rows(mutate(mm, period = "full"), mm_periods), "results/market_model.csv")
add("## Market exposure (daily log returns vs Nifty 50)", "",
    sprintf("- Beta %.2f (95%% CI %.2f to %.2f); correlation %.2f.", mm$beta, mm$beta_low, mm$beta_high, mm$correlation),
    sprintf("- The market explains %s of daily variance (R-squared); %s is company-specific.", pct(mm$r_squared, 0),
            pct(1 - mm$r_squared, 0)),
    sprintf("- Beta by period: %s.", paste(sprintf("%s %.2f", mm_periods$period, mm_periods$beta), collapse = "; ")), "")
rb <- rolling_beta(rets)
save_plot(ggplot(filter(rb, !is.na(beta)), aes(Date, beta)) +
            geom_hline(yintercept = 1, colour = INK, linetype = 2, linewidth = 0.3) +
            geom_line(colour = BLUE, linewidth = 0.6) +
            labs(title = "One-year rolling beta to the Nifty 50",
                 subtitle = sprintf("Full-period beta %.2f, but the market explains only %s of daily moves",
                                    mm$beta, pct(mm$r_squared, 0)), x = NULL, y = "Beta"), "06_rolling_beta.png", h = 4)

# ---- 5. Volatility: GARCH(1,1) -----------------------------------------------------------------------
r <- rets$stock
garch <- fit_garch(r)
add("## Volatility clustering: GARCH(1,1)", "",
    sprintf("- alpha %.3f, beta %.3f, persistence %.3f: a volatility shock halves in about %.0f trading days.",
            garch$alpha, garch$beta, garch$persistence, garch$half_life_days),
    sprintf("- Long-run volatility implied by the model: %s a year.", pct(garch$long_run_vol_annual)), "")
vol <- tibble(Date = rets$Date, garch = sqrt(garch$variance * TRADING_DAYS))
save_plot(ggplot(vol, aes(Date, garch)) + geom_line(colour = BLUE, linewidth = 0.5) +
            scale_y_continuous(labels = percent) +
            labs(title = "GARCH(1,1) estimate of annualised volatility",
                 subtitle = sprintf("Calm and turbulent periods cluster; shocks halve in about %.0f trading days",
                                    garch$half_life_days), x = NULL, y = NULL), "07_garch_volatility.png", h = 4)

# ---- 6. Value-at-Risk backtest --------------------------------------------------------------------
start <- which(rets$Date >= as.Date("2012-01-01"))[1]
var_matrix <- rolling_var(r, start_index = start, level = 0.99)
test_idx <- start:length(r)
backtest <- backtest_var(r[test_idx], var_matrix[test_idx, ], level = 0.99) %>%
  mutate(method = recode(method, historical = "Historical (500 days)", garch_normal = "GARCH, normal tails",
                         garch_fhs = "GARCH, filtered historical simulation"))
write_csv(backtest, "results/var_backtest.csv")
add(sprintf("## 99%% one-day Value-at-Risk backtest, %s to %s", rets$Date[start], max(rets$Date)), "",
    "| Method | Days | Breaches | Expected | Kupiec p | Independence p | Average VaR |", "|---|---|---|---|---|---|---|",
    sprintf("| %s | %d | %d | %.1f | %.3f | %.3f | %s |", backtest$method, backtest$days, backtest$exceedances,
            backtest$expected, backtest$kupiec_p, backtest$independence_p, pct(backtest$avg_var, 2)), "",
    "Kupiec p < 0.05: wrong breach rate. Independence p < 0.05: breaches cluster.", "")
vplot <- tibble(Date = rets$Date[test_idx], ret = r[test_idx], var = var_matrix[test_idx, "garch_fhs"]) %>%
  mutate(breach = -ret > var)
save_plot(ggplot(vplot, aes(Date)) + geom_line(aes(y = ret), colour = GREY, linewidth = 0.3) +
            geom_line(aes(y = -var), colour = BLUE, linewidth = 0.6) +
            geom_point(data = filter(vplot, breach), aes(y = ret), colour = ORANGE, size = 1.6) +
            scale_y_continuous(labels = percent) +
            labs(title = "Daily returns vs 99% VaR (GARCH, filtered historical simulation)",
                 subtitle = sprintf("%d breaches (orange) in %d days; %.1f expected", sum(vplot$breach), nrow(vplot),
                                    nrow(vplot) * 0.01),
                 x = NULL, y = "Daily log return"), "08_var_backtest.png", h = 4.2)

# ---- 7. Does unusual volume predict the next day? ------------------------------------------------------
ab_vol <- abnormal_volume(px$Volume)[-1]
ret_all <- log(px$Close / lag(px$Close))[-1]
granger <- map_dfr(c(1, 3, 5, 10), function(k) {
  g1 <- granger_test(ret_all, ab_vol, k); g2 <- granger_test(abs(ret_all), ab_vol, k)
  tibble(lags = k, direction_p = g1$p_value, direction_r2_added = g1$r2_added,
         size_p = g2$p_value, size_r2_added = g2$r2_added)
})
write_csv(granger, "results/granger.csv")
same_day <- cor(ab_vol, abs(ret_all), use = "complete.obs")
n_tests <- 2 * nrow(granger)
add("## Does abnormal volume predict the next day? (Granger tests)", "",
    sprintf("- Same day: abnormal volume correlates %.2f with the size of the move.", same_day), "",
    "| Lags | Direction p | Variance added | Size p | Variance added |", "|---|---|---|---|---|",
    sprintf("| %d | %.3f | %s | %.3f | %s |", granger$lags, granger$direction_p, pct(granger$direction_r2_added, 2),
            granger$size_p, pct(granger$size_r2_added, 2)), "",
    sprintf("- %d of %d tests have p < 0.05; with a Bonferroni correction (p < %.4f) none do.",
            sum(c(granger$direction_p, granger$size_p) < 0.05), n_tests, 0.05 / n_tests),
    sprintf("- The most volume adds to explained variance in any test is %s.",
            pct(max(c(granger$direction_r2_added, granger$size_r2_added)), 2)), "")

px_v <- tibble(abnormal_vol = ab_vol, ret = ret_all, next_ret = lead(ret_all)) %>%
  filter(!is.na(abnormal_vol), !is.na(next_ret))
p4 <- px_v %>%
  mutate(volume_group = cut(abnormal_vol, quantile(abnormal_vol, 0:5 / 5), include.lowest = TRUE,
                            labels = c("Lowest 20%", "2", "3", "4", "Highest 20%"))) %>%
  group_by(volume_group) %>%
  summarise(`Same day: average size of move` = mean(abs(ret)),
            `Next day: share of up days - 50%` = mean(next_ret > 0) - 0.5, .groups = "drop") %>%
  pivot_longer(-volume_group) %>%
  mutate(name = factor(name, levels = c("Same day: average size of move", "Next day: share of up days - 50%"))) %>%
  ggplot(aes(volume_group, value)) + geom_col(fill = BLUE, width = 0.65) + facet_wrap(~ name, scales = "free_y") +
  scale_y_continuous(labels = percent) +
  labs(title = "Unusual volume comes with big moves, but doesn't predict tomorrow's direction",
       subtitle = "Next-day bars are within +/-1.5 points of a coin flip, on about 660 days per group: noise",
       x = "Volume relative to the previous 20 days (quintiles)", y = NULL)
save_plot(p4, "04_volume_vs_moves.png", w = 10, h = 4.2)

